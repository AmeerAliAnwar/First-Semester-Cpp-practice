#include<iostream >
#include <cmath>
using namespace std;
int main ()
{
	cout<<pow(3,2);  //for power 
	cout<<endl;
	cout<<sqrt (64);  //for square root
	cout<<endl;
	cout<<min(1,9);   //for finding minimum number 
	cout<<endl;
	cout<<max (3,6);   //for finding maximum number 
	cout<<endl;
	int x = 5;
	cout<< x++;  //for increasing value by one but after printing it
	cout<<endl;
	cout<<x;      // now x will be increased by one 
	cout<<endl;
	cout<<++x;    //increase value by one and then print it
	
	return 0;
}